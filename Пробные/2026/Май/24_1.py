import re

# Читаем содержимое файла
with open('1_24.txt', 'r') as f:
    s = f.readline().strip()

# Регулярное выражение для поиска 16‑ричных чисел, оканчивающихся на чётную цифру
# [1-9A-F] — первая цифра: не может быть 0 (значащее число)
# [0-9A-F]* — любые 16‑ричные цифры далее (0 или более)
# [02468ACE] — последняя цифра должна быть чётной в 16‑ричной системе
pattern = r'[1-9A-F][0-9A-F]*[02468ACE]'
matches = re.findall(pattern, s)

if matches:
    # Находим самую длинную последовательность
    max_sequence = max(matches, key=len)
    print(len(max_sequence))
else:
    print(0)  # Если чётных 16‑ричных чисел нет
